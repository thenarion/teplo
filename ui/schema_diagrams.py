"""
Схемы узлов охлаждения.
"""
import streamlit as st


def show_liquid_cooling_scheme():
    """Схема узла жидкостного охлаждения."""
    st.subheader("Схема узла жидкостного охлаждения")

    st.markdown("""
    ```
    ┌─────────────────────────────────────────────────────────────┐
    │                    КОНТУР АНТИФРИЗА                         │
    │                                                             │
    │   Дымовые газы                                              │
    │       ↓                                                     │
    │   ┌──────────────────┐                                      │
    │   │ Газо-жидкостный  │                                      │
    │   │   теплообменник  │                                      │
    │   └────────┬─────────┘                                      │
    │            │                                                │
    │            ↓                                                │
    │   ┌──────────────────┐                                      │
    │   │ Трёхходовой      │                                      │
    │   │ клапан / байпас  │                                      │
    │   └────────┬─────────┘                                      │
    │            │                                                │
    │            ↓                                                │
    │   ┌──────────────────┐    ┌──────────────────┐              │
    │   │  Циркуляционный  │    │  Фильтр          │              │
    │   │      насос       │───→│  антифриза       │              │
    │   └──────────────────┘    └────────┬─────────┘              │
    │            ↑                       │                        │
    │            │                       ↓                        │
    │   ┌────────┴─────────┐    ┌──────────────────┐              │
    │   │   Dry cooler /   │    │  Воздухоотводчик  │              │
    │   │   АВО с вентиля- │←───│                   │              │
    │   │   торами         │    └──────────────────┘              │
    │   └────────┬─────────┘                                      │
    │            │                                                │
    │            ↓                                                │
    │   ┌──────────────────┐    ┌──────────────────┐              │
    │   │ Расширительный   │    │ Предохранительный│              │
    │   │ мембранный бак   │    │     клапан       │              │
    │   └──────────────────┘    └──────────────────┘              │
    │                                                             │
    │   Датчики: T вход/выход, P контур, расход                  │
    │   Система подпитки/заправки                                 │
    └─────────────────────────────────────────────────────────────┘
    ```
    """)

    st.markdown("""
    **Состав узла:**
    1. Газо-жидкостный теплообменник на дымовых газах
    2. Циркуляционный насос антифриза
    3. Расширительный мембранный бак
    4. Предохранительный клапан
    5. Воздухоотводчик
    6. Фильтр антифриза
    7. Трёхходовой регулирующий клапан или байпас
    8. Аппарат воздушного охлаждения (dry cooler / АВО) с вентиляторами
    9. Датчики температуры, давления, расхода
    10. Система подпитки или заправки
    """)

    st.markdown("""
    **Рекомендации:**
    - Использовать закрытый контур
    - Антифриз с ингибиторами коррозии
    - Предусмотреть байпас для регулирования температуры
    - Зимой — регулирование вентиляторов для защиты от переохлаждения
    - Защита от перегрева теплоносителя
    - Контроль давления в контуре
    - Пробоотбор и контроль состояния гликоля
    """)


def show_gas_air_cooling_scheme():
    """Схема газовоздушного охлаждения."""
    st.subheader("Схема газовоздушного охлаждения")

    st.markdown("""
    ```
    Дымовые газы (горячие)
         ↓
    ┌─────────────────────────┐
    │                         │
    │   Газовоздушный         │
    │   теплообменник         │
    │   (оребрённые трубы)    │
    │                         │
    └─────────┬───────────────┘
              │
              ↓
    Дымовые газы (охлаждённые) → далее в тракт

    Наружный воздух
         ↓ (вентилятор)
    ┌─────────────────────────┐
    │                         │
    │   Проходит через        │
    │   оребрённый пучок      │
    │                         │
    └─────────┬───────────────┘
              │
              ↓
    Нагретый воздух → в атмосферу
    ```
    """)
